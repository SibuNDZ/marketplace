-- ============================================================
-- 3. products: category_id, handmade, tags
-- ============================================================

ALTER TABLE products ADD COLUMN category_id BIGINT NULL;
ALTER TABLE products ADD COLUMN handmade    BOOLEAN NOT NULL DEFAULT FALSE;

-- TEXT[] rather than a product_tags join table. Tags are read with the
-- product, never independently, and are always replaced wholesale on edit
-- — the two things that make a join table worth its cost (querying tags on
-- their own, mutating one at a time) do not apply. GIN indexed so
-- "products having tag X" stays an index scan.
ALTER TABLE products ADD COLUMN tags TEXT[] NOT NULL DEFAULT '{}';

CREATE INDEX idx_products_tags ON products USING GIN (tags);

-- Map the five old enum values onto the new tree. Everything lands on a
-- TOP-LEVEL category: the old data has no information about which
-- subcategory a product belongs in, and guessing would be worse than
-- leaving vendors to refine it themselves.
UPDATE products p SET category_id = c.id
FROM public.categories c
WHERE c.parent_id IS NULL
  AND c.slug = CASE p.category
      WHEN 'PRODUCE' THEN 'produce'
      WHEN 'PANTRY'  THEN 'pantry'
      WHEN 'CRAFTS'  THEN 'art-and-crafts'
      WHEN 'HOME'    THEN 'home-and-living'
      ELSE 'other'
  END;

-- The judgement call flagged at the top: picking CRAFTS was a vendor
-- saying "I made this", so that intent is preserved as the flag rather
-- than dropped on the floor when the category is renamed.
UPDATE products SET handmade = TRUE WHERE category = 'CRAFTS';

-- Safety net. If any row failed to map, the NOT NULL below would fail with
-- a constraint error naming a column, not a cause. This fails with the
-- reason instead.
DO $$
DECLARE unmapped INT;
BEGIN
    SELECT COUNT(*) INTO unmapped FROM products WHERE category_id IS NULL;
    IF unmapped > 0 THEN
        RAISE EXCEPTION 'V14: % product(s) did not map to a category', unmapped;
    END IF;
END $$;

ALTER TABLE products ALTER COLUMN category_id SET NOT NULL;
ALTER TABLE products ADD CONSTRAINT fk_product_category
    FOREIGN KEY (category_id) REFERENCES public.categories(id) ON DELETE RESTRICT;

-- Replaces idx_products_category_live from V10, same shape and purpose.
CREATE INDEX idx_products_category_id_live ON products (category_id)
    WHERE deleted_at IS NULL;
DROP INDEX IF EXISTS idx_products_category_live;

-- Partial index for the handmade filter chip, matching the live-catalogue
-- pattern above: only TRUE rows are ever filtered on, so only they are
-- worth indexing.
CREATE INDEX idx_products_handmade_live ON products (handmade)
    WHERE deleted_at IS NULL AND handmade = TRUE;

-- ============================================================
-- 4. Drop the old enum column
-- ============================================================
-- Dropped, not left behind. V12 left dead shipping columns in place and
-- had to write a comment explaining they were dead; two columns answering
-- "what category is this" is exactly the ambiguity that costs an afternoon
-- later. The data is fully carried over above, and the check above proves
-- it before this runs.
--
-- Rollback note: reverting past V14 needs a restore, since the enum values
-- only exist in this file after it runs.

ALTER TABLE products DROP CONSTRAINT IF EXISTS products_category_check;
ALTER TABLE products DROP COLUMN category;
