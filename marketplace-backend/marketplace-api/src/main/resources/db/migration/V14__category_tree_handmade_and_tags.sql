-- V14__category_tree_handmade_and_tags.sql
-- Categories move from a Java enum to a table, "handmade" becomes a flag
-- instead of a category, and products gain free-form tags.
--
-- ============================================================
-- WHY A TABLE
-- ============================================================
-- V10 put five categories in an enum with a CHECK constraint, and wrote
-- down the cost itself: "If ProductCategory ever gains a value, the enum
-- AND a follow-up migration updating this CHECK must change together."
-- Every vendor asking for a new category was a code change, a migration,
-- a redeploy, and a matching edit to the frontend's data/categories.ts.
-- A table makes that an admin insert.
--
-- ============================================================
-- WHY HANDMADE IS NOT A CATEGORY
-- ============================================================
-- With CRAFTS as a category, a handmade beaded necklace had to be either
-- Crafts or Fashion>Jewellery, and the vendor had to guess. Shoppers
-- looking for a necklace browse Jewellery; shoppers who care about
-- handmade want it across the whole catalogue. Category answers "what is
-- it", handmade answers "how was it made" — independent questions, so
-- independent fields.
--
-- Existing CRAFTS products are therefore migrated to Art and crafts AND
-- flagged handmade. That is the honest reading of what the vendor meant
-- when they picked CRAFTS, and it is the one mapping in this migration
-- that is a judgement call rather than a rename.

-- ============================================================
-- 1. categories
-- ============================================================
-- Two levels only, enforced by the CHECK below: a subcategory's parent
-- must itself be top-level. Arbitrary depth sounds free but is not — the
-- chip row, the breadcrumb, and the "count everything beneath me" query
-- all get materially harder, and nobody has asked for Produce > Fruit >
-- Citrus. This constraint is cheap to drop later and expensive to have
-- omitted, because by then there is depth-3 data to clean up.
--
-- NOTE: no product_count column. The spec called for one, denormalised
-- and refreshed on write. Deferred deliberately — see the comment on the
-- count query in CategoryService. Adding it later is one migration and
-- does not change the API shape.

-- Depth is enforced declaratively, with no trigger and no subquery (a CHECK
-- cannot contain one — Postgres rejects it outright). The trick:
--
--   depth        is 0 for a root, 1 for a child.
--   parent_depth is NULL for a root, and always literally 0 for a child.
--   the FK points (parent_id, parent_depth) at (id, depth).
--
-- So a child can only reference a parent whose depth is 0, i.e. a root.
-- A grandchild would need its parent to have depth 0, but any row with a
-- parent has depth 1, so the reference cannot resolve and the insert
-- fails. Both columns are GENERATED, so neither the app nor an admin can
-- put them out of step with parent_id.
--
-- Composite FKs default to MATCH SIMPLE: a row with any NULL in the
-- referencing columns satisfies it. That is exactly what lets roots
-- (parent_depth NULL) sit in the same table without a second constraint.

CREATE TABLE public.categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT      NULL,
    name        VARCHAR(80) NOT NULL,
    slug        VARCHAR(80) NOT NULL,
    icon        VARCHAR(16) NULL,
    sort_order  INT         NOT NULL DEFAULT 0,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,

    depth        SMALLINT GENERATED ALWAYS AS
                 (CASE WHEN parent_id IS NULL THEN 0 ELSE 1 END) STORED,
    parent_depth SMALLINT GENERATED ALWAYS AS
                 (CASE WHEN parent_id IS NULL THEN NULL ELSE 0 END) STORED,

    CONSTRAINT uq_categories_slug     UNIQUE (slug),
    CONSTRAINT uq_categories_id_depth UNIQUE (id, depth),
    CONSTRAINT categories_no_self_parent CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT fk_category_parent_is_top FOREIGN KEY (parent_id, parent_depth)
        REFERENCES public.categories (id, depth) ON DELETE RESTRICT
);

-- ON DELETE RESTRICT, not CASCADE: deleting Fashion should not silently
-- take seven subcategories and orphan every product under them. Deleting
-- a category with children must be a deliberate two-step.

CREATE INDEX idx_categories_parent ON public.categories (parent_id);

